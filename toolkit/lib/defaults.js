// استبدال المتغيرات في الرد
function fillTemplate(text, name) {
  const isPhone = /^[+\d\s()-]{6,}$/.test(name || '');
  const full = isPhone ? '' : (name || '').replace(/^~\s*/, '').trim();
  const first = full.split(/\s+/)[0] || '';
  const days = ['الأحد', 'الاتنين', 'التلات', 'الأربع', 'الخميس', 'الجمعة', 'السبت'];
  const d = new Date();
  let t = String(text);
  if (!first) t = t.replace(/\s*يا\s*\{الاسم(_الأول)?\}/g, ''); // "تمام يا {الاسم}" ← "تمام" لو الاسم مش معروف
  return t
    .replace(/\{الاسم_الأول\}/g, first)
    .replace(/\{الاسم\}/g, full)
    .replace(/\{اليوم\}/g, days[d.getDay()])
    .replace(/\{التاريخ\}/g, d.toLocaleDateString('ar-EG'))
    .replace(/ +([،,!؟?.])/g, '$1')
    .replace(/ {2,}/g, ' ');
}
